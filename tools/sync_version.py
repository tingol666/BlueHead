"""Generate language-specific version constants from pyproject.toml."""
from pathlib import Path
import argparse
import re
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def generated_files():
    version = tomllib.loads((ROOT / 'pyproject.toml').read_text('utf-8'))['project']['version']
    if not re.fullmatch(r'\d+\.\d+\.\d+', version):
        raise ValueError('Release version must contain three numeric parts')
    return {
        ROOT / 'bluehead/__init__.py': (
            '"""BlueHead: Bluetooth receiver, based on the Apache-2.0 Bumble stack."""\n'
            '# Generated by tools/sync_version.py from pyproject.toml.\n'
            f'__version__ = "{version}"\n'),
        ROOT / 'desktop/BlueHead.Version.props': (
            '<!-- Generated by tools/sync_version.py from pyproject.toml. -->\n'
            '<Project>\n  <PropertyGroup>\n'
            f'    <Version>{version}</Version>\n'
            f'    <InformationalVersion>{version}</InformationalVersion>\n'
            '  </PropertyGroup>\n</Project>\n'),
    }


def check():
    stale = [p.relative_to(ROOT).as_posix() for p, text in generated_files().items()
             if not p.is_file() or p.read_text('utf-8') != text]
    if stale:
        raise RuntimeError('Run tools/sync_version.py before building: ' + ', '.join(stale))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        check()
    else:
        for file, content in generated_files().items():
            file.write_text(content, 'utf-8', newline='\n')
    print('Version constants are consistent')
